import { router, useForm, usePage } from '@inertiajs/react';
import { useCallback, useEffect, useState } from 'react';
import type { FormEvent } from 'react';
import { Alert } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Modal } from '@/components/ui/modal';
import { PageHeader } from '@/components/page-header';
import { useT } from '@/hooks/use-t';
import AppLayout from '@/layouts/app-layout';
import { fortify } from '@/lib/fortify';

async function getJson<T>(url: string): Promise<T> {
    const response = await fetch(url, {
        credentials: 'same-origin',
        headers: {
            Accept: 'application/json',
            'X-Requested-With': 'XMLHttpRequest',
        },
    });

    if (!response.ok) {
        throw new Error(`Request failed: ${response.status}`);
    }

    return response.json() as Promise<T>;
}

function PasswordCard() {
    const { t } = useT();
    const form = useForm({
        current_password: '',
        password: '',
        password_confirmation: '',
    });

    const submit = (event: FormEvent) => {
        event.preventDefault();
        form.put(fortify.password, {
            errorBag: 'updatePassword',
            preserveScroll: true,
            onSuccess: () => form.reset(),
        });
    };

    return (
        <Card
            title={t('Password')}
            description={t('Use a long, unique password.')}
        >
            <form onSubmit={submit} className="space-y-4">
                <Input
                    label={t('Current password')}
                    type="password"
                    autoComplete="current-password"
                    value={form.data.current_password}
                    onChange={(e) =>
                        form.setData('current_password', e.target.value)
                    }
                    error={form.errors.current_password}
                />
                <Input
                    label={t('New password')}
                    type="password"
                    autoComplete="new-password"
                    value={form.data.password}
                    onChange={(e) => form.setData('password', e.target.value)}
                    error={form.errors.password}
                />
                <Input
                    label={t('Confirm new password')}
                    type="password"
                    autoComplete="new-password"
                    value={form.data.password_confirmation}
                    onChange={(e) =>
                        form.setData('password_confirmation', e.target.value)
                    }
                    error={form.errors.password_confirmation}
                />
                <div className="flex items-center gap-3">
                    <Button type="submit" loading={form.processing}>
                        {t('Update password')}
                    </Button>
                    {form.recentlySuccessful && (
                        <span className="text-sm text-success" role="status">
                            {t('Saved.')}
                        </span>
                    )}
                </div>
            </form>
        </Card>
    );
}

function TwoFactorSetup() {
    const { t } = useT();
    const [qr, setQr] = useState<string | null>(null);
    const [secret, setSecret] = useState<string | null>(null);
    const form = useForm({ code: '' });

    useEffect(() => {
        void getJson<{ svg: string }>(fortify.twoFactorQrCode).then((r) =>
            setQr(r.svg),
        );
        void getJson<{ secretKey: string }>(fortify.twoFactorSecretKey).then(
            (r) => setSecret(r.secretKey),
        );
    }, []);

    const submit = (event: FormEvent) => {
        event.preventDefault();
        form.post(fortify.twoFactorConfirm, {
            errorBag: 'confirmTwoFactorAuthentication',
            preserveScroll: true,
        });
    };

    return (
        <div className="space-y-4">
            <Alert variant="info">
                {t(
                    'Scan this QR code with an authenticator app, then enter the 6-digit code to finish.',
                )}
            </Alert>
            <div className="flex flex-col items-start gap-5 sm:flex-row">
                {qr ? (
                    <div
                        role="img"
                        aria-label={t('Two-factor QR code')}
                        className="size-48 shrink-0 rounded-box border border-base-300 bg-white p-3 [&>svg]:block [&>svg]:size-full"
                        // SVG is generated by Fortify on the server.
                        dangerouslySetInnerHTML={{ __html: qr }}
                    />
                ) : (
                    <div
                        aria-hidden
                        className="size-48 shrink-0 animate-pulse rounded-box bg-base-200"
                    />
                )}
                <div className="min-w-0 space-y-2 text-sm">
                    <p className="font-medium">{t("Can't scan the code?")}</p>
                    <p className="text-base-content/70">
                        {t('Enter this key in your authenticator app instead:')}
                    </p>
                    {secret && (
                        <code className="block rounded-field bg-base-200 px-3 py-2 font-mono break-all select-all">
                            {secret}
                        </code>
                    )}
                </div>
            </div>
            <form onSubmit={submit} className="space-y-4">
                <Input
                    label={t('Authentication code')}
                    inputMode="numeric"
                    autoComplete="one-time-code"
                    value={form.data.code}
                    onChange={(e) => form.setData('code', e.target.value)}
                    error={form.errors.code}
                />
                <Button type="submit" loading={form.processing}>
                    {t('Confirm and enable')}
                </Button>
            </form>
        </div>
    );
}

function RecoveryCodes() {
    const { t } = useT();
    const [codes, setCodes] = useState<string[] | null>(null);

    const load = useCallback(() => {
        void getJson<string[]>(fortify.recoveryCodes).then(setCodes);
    }, []);

    useEffect(load, [load]);

    const regenerate = () =>
        router.post(
            fortify.recoveryCodes,
            {},
            { preserveScroll: true, onSuccess: load },
        );

    return (
        <div className="space-y-3">
            <p className="text-sm">
                {t(
                    'Store these recovery codes in a password manager. Each code can be used once if you lose your authenticator.',
                )}
            </p>
            {codes && (
                <ul className="grid gap-1 rounded-box bg-base-200 p-4 font-mono text-sm">
                    {codes.map((code) => (
                        <li key={code}>{code}</li>
                    ))}
                </ul>
            )}
            <Button variant="soft" size="sm" onClick={regenerate}>
                {t('Regenerate recovery codes')}
            </Button>
        </div>
    );
}

export default function Security() {
    const { t } = useT();
    const { auth } = usePage().props;
    const [confirmDisable, setConfirmDisable] = useState(false);
    const [disabling, setDisabling] = useState(false);

    const enable = () =>
        router.post(fortify.twoFactor, {}, { preserveScroll: true });

    const disable = () =>
        router.delete(fortify.twoFactor, {
            preserveScroll: true,
            onStart: () => setDisabling(true),
            onFinish: () => {
                setDisabling(false);
                setConfirmDisable(false);
            },
        });

    return (
        <AppLayout title={t('Security')}>
            <PageHeader
                title={t('Security')}
                description={t(
                    'Protect your account. Two-factor authentication is optional but strongly recommended.',
                )}
            />
            <div className="grid items-start gap-6 xl:grid-cols-2">
                <Card
                    title={t('Two-factor authentication')}
                    description={t(
                        'Adds a second step to every login. Strongly recommended: this panel controls your server.',
                    )}
                >
                    {auth.twoFactor.enabled ? (
                        <div className="space-y-4">
                            <Alert variant="success">
                                {t('Two-factor authentication is on.')}
                            </Alert>
                            <RecoveryCodes />
                            <Button
                                variant="error"
                                size="sm"
                                onClick={() => setConfirmDisable(true)}
                            >
                                {t('Disable two-factor authentication')}
                            </Button>
                        </div>
                    ) : auth.twoFactor.pending ? (
                        <TwoFactorSetup />
                    ) : (
                        <div className="space-y-4">
                            <Alert variant="warning">
                                {t('Two-factor authentication is off.')}
                            </Alert>
                            <Button onClick={enable}>{t('Enable')}</Button>
                        </div>
                    )}
                </Card>

                <PasswordCard />
            </div>

            <Modal
                open={confirmDisable}
                onClose={() => setConfirmDisable(false)}
                title={t('Disable two-factor authentication?')}
                size="sm"
                footer={
                    <>
                        <Button
                            variant="ghost"
                            onClick={() => setConfirmDisable(false)}
                        >
                            {t('Cancel')}
                        </Button>
                        <Button
                            variant="error"
                            loading={disabling}
                            onClick={disable}
                        >
                            {t('Disable')}
                        </Button>
                    </>
                }
            >
                {t('Your account will be protected by your password only.')}
            </Modal>
        </AppLayout>
    );
}
